// Generates supabase/migrations/0002_seed_foods.sql from src/lib/foods.ts so the database copy
// of the reference foods never drifts from the copy bundled in the app.
import { readFileSync, writeFileSync } from 'node:fs'
const src = readFileSync(new URL('../src/lib/foods.ts', import.meta.url), 'utf8')
const body = src.slice(src.indexOf('const R: Row[] = [') + 'const R: Row[] = '.length, src.indexOf('\n]\n') + 2)
const rows = new Function(`return ${body}`)()
const q = s => `'${String(s).replace(/'/g, "''")}'`
const values = rows.map(([id, name, cat, kcal, p, c, f, fb, source, servings, , unit]) =>
  `  (${q(id)}, ${q(name)}, ${q(cat)}, ${q(unit ?? 'g')}, ${kcal}, ${p}, ${c}, ${f}, ${fb}, ${q(JSON.stringify(servings))}::jsonb, ${q(source)})`)
writeFileSync(new URL('../supabase/migrations/0002_seed_foods.sql', import.meta.url),
`-- Built-in reference foods (per 100 g / 100 ml). Generated by scripts/build-seed.mjs — do not edit by hand.
-- source 'usda'   = rounded standard-reference value for the plain food (USDA FoodData Central)
-- source 'recipe' = typical value for a mixed dish; real recipes vary
insert into public.foods (ref_key, name, category, unit, kcal, protein_g, carbs_g, fat_g, fibre_g, servings, source) values
${values.join(',\n')}
on conflict (ref_key) do update set name = excluded.name, category = excluded.category, unit = excluded.unit, kcal = excluded.kcal,
  protein_g = excluded.protein_g, carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, fibre_g = excluded.fibre_g,
  servings = excluded.servings, source = excluded.source;
`)
console.log(`Wrote ${rows.length} foods`)
